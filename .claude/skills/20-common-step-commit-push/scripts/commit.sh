readonly SCRIPT_PREFIX="CP"
readonly EXCLUDE_FILE=".claude/skills/20-common-step-commit-push/assets/exclude-patterns.txt"
readonly MESSAGE_RE='^(feat|fix|docs|chore|refactor|test|perf|build|ci|ai-asset): .+$'
# AI 生成を示すフッター・モデル名（大文字小文字を区別しない）。本文の語としての「Claude Code」等は対象にせず、フッター形と機械的なモデル名だけを見る
readonly FOOTER_RE='(co-authored-by:|generated with|generated by|signed-off-by:.*(claude|anthropic|openai)|noreply@anthropic\.com|🤖|claude-(opus|sonnet|haiku|fable|mythos)[-0-9.]*|claude (opus|sonnet|haiku|fable|mythos) [0-9]|gpt-[0-9]|chatgpt|github copilot|gemini-[0-9])'

usage() {
  cat <<'USAGE'
使い方: bash .claude/skills/20-common-step-commit-push/scripts/commit.sh -m "<メッセージ>" [--allow-empty] <ファイル>...
  -m <メッセージ>   `<prefix>: <日本語 1 行>`（prefix: feat fix docs chore refactor test perf build ci ai-asset）
  --allow-empty     差分が無くてもコミットする（MR 作成時の空コミットのみ）
  <ファイル>...     コミットする対象（リポジトリルート相対）。-A / . / glob は受け付けない
USAGE
}

EXCLUDED=()   # "<path>（<pattern>）"
print_excluded() {
  if [ "${#EXCLUDED[@]}" -eq 0 ]; then printf '除外: なし\n'; else printf '除外: %s\n' "$(IFS=,; printf '%s' "${EXCLUDED[*]}")"; fi
}
result_ok() { # $1=メッセージ
  log_info "OK: $1"
  printf 'OK: %s\n' "$1"
  exit 0
}
result_ng() { # $1=番号 $2=メッセージ $3=終了コード
  log_warn "${SCRIPT_PREFIX}$1: $2"
  printf '%s%s: %s\n' "$SCRIPT_PREFIX" "$1" "$2"
  exit "$3"
}

# 除外パターンに一致すればパターンを REPLY に入れて 0
matches_exclude() { # $1=パス
  local path="$1" base="${1##*/}" pat
  REPLY=""
  [ -f "$EXCLUDE_FILE" ] || return 1
  while IFS= read -r pat || [ -n "$pat" ]; do
    pat="${pat%$'\r'}"
    pat="${pat#"${pat%%[![:space:]]*}"}"
    [ -z "$pat" ] && continue
    case "$pat" in \#*) continue ;; esac
    # shellcheck disable=SC2053
    if [[ "$pat" == */* ]]; then
      [[ "$path" == $pat ]] && { REPLY="$pat"; return 0; }
    else
      [[ "$base" == $pat ]] && { REPLY="$pat"; return 0; }
    fi
  done < "$EXCLUDE_FILE"
  return 1
}

# 削除・リネーム元が既にステージされていれば 0（index と HEAD を、リネーム検出を切って比べる）
has_staged_diff() { # $1=パス
  git rev-parse --verify -q HEAD >/dev/null 2>&1 || return 1
  [ -n "$(git diff --cached --no-renames --name-only -- "$1" 2>/dev/null | tr -d '\r')" ]
}

main() {
  local message="" allow_empty=0 files=() f
  # 1. 引数（順不同）
  while [ $# -gt 0 ]; do
    case "$1" in
      -h|--help) usage; exit 0 ;;
      -m)
        [ $# -ge 2 ] || result_ng 007 "-m にメッセージが無い（引数の誤り。期待する形式: -m \"<prefix>: <日本語 1 行>\"）" 2
        message="$2"; shift ;;
      -m*) message="${1#-m}" ;;
      --allow-empty) allow_empty=1 ;;
      -A|--all|-a|.|./|..) result_ng 001 "一括指定（$1）は受け付けない。自分が変更したファイルだけをパスで明示する" 2 ;;
      --amend|--no-verify) result_ng 007 "$1 は存在しないオプション（直前コミットの書き換え・検査の回避はしない）" 2 ;;
      -*) result_ng 007 "不明なオプション: $1（-m <メッセージ> / --allow-empty / <ファイル>...）" 2 ;;
      *)
        case "$1" in
          *'*'*|*'?'*|*'['*) result_ng 001 "glob（$1）は受け付けない。パスを 1 つずつ明示する" 2 ;;
        esac
        f="${1#./}"
        # ディレクトリ（symlink 経由を含む）は受け付けない。除外パターンは指定されたパスにしか当たらず、中の .env 等を見落とすため
        if [ -d "$f" ]; then result_ng 001 "ディレクトリ（$f）は受け付けない。除外パターンはファイル単位で当たるので、中のファイルをパスで明示する" 2; fi
        files+=("$f") ;;
    esac
    shift
  done

  cd "$LOGGER_ROOT" || result_ng 007 "リポジトリルートに移動できない（環境の誤り）: $LOGGER_ROOT" 2
  log_info "start message='${message}' files=${files[*]:-} allow_empty=$allow_empty"

  # 1. メッセージの検査
  [ -n "$message" ] || result_ng 002 "メッセージが無い。期待する形式: <prefix>: <日本語 1 行>（prefix: feat fix docs chore refactor test perf build ci ai-asset）" 1
  case "$message" in *$'\n'*) result_ng 002 "メッセージは 1 行にする（改行を含む）。期待する形式: <prefix>: <日本語 1 行>" 1 ;; esac
  [[ "$message" =~ $MESSAGE_RE ]] || result_ng 002 "メッセージ規約違反: '$message'。期待する形式: <prefix>: <日本語 1 行>（prefix: feat fix docs chore refactor test perf build ci ai-asset）" 1
  local lower="${message,,}"
  if [[ "$lower" =~ $FOOTER_RE ]]; then
    result_ng 002 "AI 生成を示すフッター・モデル名を含む（検出: '${BASH_REMATCH[0]}'）。期待する形式: <prefix>: <日本語 1 行> のみ" 1
  fi

  # 2. 対象の検査
  if [ "${#files[@]}" -eq 0 ] && [ "$allow_empty" -eq 0 ]; then
    result_ng 001 "対象ファイルが未指定。自分が変更したファイルだけをパスで明示する（空コミットは --allow-empty）" 2
  fi

  # 3. 除外パターン
  local kept=()
  for f in "${files[@]}"; do
    if matches_exclude "$f"; then EXCLUDED+=("$f（$REPLY）"); else kept+=("$f"); fi
  done
  if [ "${#files[@]}" -gt 0 ] && [ "${#kept[@]}" -eq 0 ]; then
    print_excluded
    result_ng 003 "対象がすべて除外パターンに一致した（${EXCLUDED[*]}）。除外パターンは $EXCLUDE_FILE" 1
  fi

  # 4. 対象の振り分け（ステージ対象 / ステージ済み）とステージ・差分の検査
  local add_err to_add=()
  if [ "${#kept[@]}" -gt 0 ]; then
    # 作業ツリーにも index にも無いパスは、削除・リネーム元が既にステージされているなら add し直さない
    for f in "${kept[@]}"; do
      if [ -e "$f" ] || [ -L "$f" ] || git ls-files --error-unmatch -- "$f" >/dev/null 2>&1; then
        to_add+=("$f")
      elif ! has_staged_diff "$f"; then
        print_excluded
        result_ng 001 "作業ツリーにも追跡対象にも無く、ステージ済みの差分も無いパスがある（$f）。綴りを確かめる（削除したファイルなら、その削除がステージされているか作業ツリーから消えているだけかを確かめる）" 2
      fi
    done
    if [ "${#to_add[@]}" -gt 0 ] && ! add_err="$(git add -- "${to_add[@]}" 2>&1)"; then
      print_excluded
      printf '%s\n' "$add_err"
      result_ng 001 "git がステージできないパスがある（.gitignore 対象・権限など）。上の git の出力を確認する" 2
    fi
    # 実際にステージされたパスに除外パターンを当て直す（指定と実パスが異なる経路の保険）。一致があれば index から戻して止まる
    local staged_ng=() s
    while IFS= read -r s; do
      [ -n "$s" ] || continue
      if matches_exclude "$s"; then git reset -q -- "$s" >/dev/null 2>&1 || true; staged_ng+=("$s（$REPLY）"); fi
    done < <(git diff --cached --name-only -- "${kept[@]}" | tr -d '\r')
    if [ "${#staged_ng[@]}" -gt 0 ]; then
      EXCLUDED+=("${staged_ng[@]}")
      print_excluded
      result_ng 003 "ステージされたパスに除外パターンの一致がある（${staged_ng[*]}）。index から戻した。対象を見直す" 1
    fi
    if git diff --cached --quiet -- "${kept[@]}" && [ "$allow_empty" -eq 0 ]; then
      print_excluded
      result_ng 004 "差分が無い（${kept[*]}）。空コミットは --allow-empty（MR 作成時のみ）に限る" 1
    fi
  fi

  # 5. コミット（amend・--no-verify に相当するオプションは持たない）
  local out sha committed
  local args=(commit -q -m "$message")
  [ "$allow_empty" -eq 1 ] && args+=(--allow-empty)
  if [ "${#kept[@]}" -gt 0 ]; then
    if ! out="$(git "${args[@]}" -- "${kept[@]}" 2>&1)"; then
      print_excluded
      printf '%s\n' "$out"
      result_ng 008 "git commit が失敗した（コミット時の検査・フック）。上の出力を確認して原因を直し、再実行する（amend や --no-verify は無い）" 1
    fi
  else
    if ! out="$(git "${args[@]}" 2>&1)"; then
      print_excluded
      printf '%s\n' "$out"
      result_ng 008 "git commit が失敗した（コミット時の検査・フック）。上の出力を確認して原因を直し、再実行する（amend や --no-verify は無い）" 1
    fi
  fi

  # 6. 出力
  sha="$(git rev-parse --short HEAD)"
  committed="$(git show --pretty=format: --name-status HEAD | sed '/^$/d')"
  printf 'コミット %s: %s\n' "$sha" "$message"
  [ -n "$committed" ] && printf '%s\n' "$committed"
  print_excluded
  local n
  n="$(printf '%s\n' "$committed" | sed '/^$/d' | wc -l | tr -d ' ')"
  log_info "committed sha=$sha files=$n excluded=${#EXCLUDED[@]}"
  result_ok "${n} ファイルをコミットした（${sha}）。除外: $([ "${#EXCLUDED[@]}" -eq 0 ] && printf 'なし' || printf '%s' "${EXCLUDED[*]}")"
}

main "$@"
